"""Export learned TF-IDF and linear weights; browser and API share estimator math."""
import json
import subprocess
from pathlib import Path
import numpy as np
from sklearn.pipeline import FeatureUnion
from sklearn.naive_bayes import MultinomialNB
from sklearn.calibration import CalibratedClassifierCV
from ml.preprocess import VARIANTS

ROOT=Path(__file__).resolve().parents[1]

def export_model(model,train,val,test):
    calibrated=isinstance(model,CalibratedClassifierCV)
    cc=model.calibrated_classifiers_[0] if calibrated else None
    pipe=cc.estimator if calibrated else model
    estimator=pipe.named_steps['model'];feat=pipe.named_steps['features']
    vectors=feat.transformer_list if isinstance(feat,FeatureUnion) else [('single',feat)]
    data={'labels':model.classes_.tolist(),'variants':VARIANTS,'vectorizers':[],
          'threshold':.55,'margin':.10,'train_rows':len(train),
          'training_source':'data/train.csv; exact selected model export'}
    for _,vec in vectors:
        data['vectorizers'].append(dict(vocabulary={k:int(v) for k,v in vec.vocabulary_.items()},idf=vec.idf_.tolist(),
            analyzer=vec.analyzer,ngram=list(vec.ngram_range),sublinear_tf=vec.sublinear_tf))
    if isinstance(estimator,MultinomialNB):
        data.update(kind='nb',weights=estimator.feature_log_prob_.tolist(),bias=estimator.class_log_prior_.tolist())
    else:
        data.update(kind='calibrated_svm' if calibrated else 'logistic',weights=estimator.coef_.tolist(),bias=estimator.intercept_.tolist())
    if calibrated:
        data['calibration']=[dict(a=float(c.a_),b=float(c.b_)) for c in cc.calibrators]
    (ROOT/'js/model-data.js').write_text('/* Exact learned estimator; generated by ml/export.py. */\nwindow.AGRI_MODEL='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
    examples=pd_concat_queries(train,val,test)
    predictions=[]
    for text in examples:
        predictions.append(dict(query=text,probabilities=model.predict_proba([text])[0].tolist(),intent=model.predict([text])[0]))
    (ROOT/'reports/export_parity_cases.json').write_text(json.dumps(predictions,ensure_ascii=False),encoding='utf8')
    print('Exported exact browser model; parity cases:',len(predictions),flush=True)

def pd_concat_queries(train,val,test):
    return (train['query'].sample(min(20,len(train)),random_state=42).tolist()+
            val['query'].sample(min(20,len(val)),random_state=42).tolist()+
            test['query'].sample(min(20,len(test)),random_state=42).tolist()+
            ['పత్తికి నీరు ఎప్పుడు పెట్టాలి','hello qzxw','naaku vari ki leaf spot vachindi'])
